//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/ydb-platform/ydb-go-genproto/protos/Ydb"
	"github.com/ydb-platform/ydb-go-genproto/protos/Ydb_Query"
	"google.golang.org/protobuf/reflect/protoreflect"
)

type fieldSpec struct {
	message  protoreflect.MessageDescriptor
	name     protoreflect.Name
	constant string
	kind     protoreflect.Kind
	repeated bool
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	part := (&Ydb_Query.ExecuteQueryResponsePart{}).ProtoReflect().Descriptor()
	resultSet := (&Ydb.ResultSet{}).ProtoReflect().Descriptor()
	value := (&Ydb.Value{}).ProtoReflect().Descriptor()
	pair := (&Ydb.ValuePair{}).ProtoReflect().Descriptor()
	fields := []fieldSpec{
		{part, "result_set", "wirePartResultSetField", protoreflect.MessageKind, false},
		{resultSet, "rows", "wireResultSetRowsField", protoreflect.MessageKind, true},
		{value, "items", "wireValueItemsField", protoreflect.MessageKind, true},
		{value, "bool_value", "wireValueBoolField", protoreflect.BoolKind, false},
		{value, "int32_value", "wireValueInt32Field", protoreflect.Sfixed32Kind, false},
		{value, "uint32_value", "wireValueUint32Field", protoreflect.Fixed32Kind, false},
		{value, "int64_value", "wireValueInt64Field", protoreflect.Sfixed64Kind, false},
		{value, "uint64_value", "wireValueUint64Field", protoreflect.Fixed64Kind, false},
		{value, "float_value", "wireValueFloatField", protoreflect.FloatKind, false},
		{value, "double_value", "wireValueDoubleField", protoreflect.DoubleKind, false},
		{value, "bytes_value", "wireValueBytesField", protoreflect.BytesKind, false},
		{value, "text_value", "wireValueTextField", protoreflect.StringKind, false},
		{value, "null_flag_value", "wireValueNullField", protoreflect.EnumKind, false},
		{value, "nested_value", "wireValueNestedField", protoreflect.MessageKind, false},
		{value, "low_128", "wireValueLow128Field", protoreflect.Fixed64Kind, false},
	}
	if err := writeFields("wire_fields_gen.go", "query", fields); err != nil {
		return err
	}
	valueFields := make([]fieldSpec, 0, len(fields))
	for _, spec := range fields[2:] {
		spec.constant = strings.TrimPrefix(spec.constant, "wire")
		valueFields = append(valueFields, spec)
	}
	valueFields = append(valueFields,
		fieldSpec{value, "pairs", "ValuePairsField", protoreflect.MessageKind, true},
		fieldSpec{value, "variant_index", "ValueVariantIndexField", protoreflect.Uint32Kind, false},
		fieldSpec{value, "high_128", "ValueHigh128Field", protoreflect.Fixed64Kind, false},
		fieldSpec{pair, "key", "PairKeyField", protoreflect.MessageKind, false},
		fieldSpec{pair, "payload", "PairPayloadField", protoreflect.MessageKind, false},
	)

	return writeFields("../wirevalue/fields_gen.go", "wirevalue", valueFields)
}

func writeFields(path, pkg string, fields []fieldSpec) error {
	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by go generate wire_value.go; DO NOT EDIT.")
	fmt.Fprintln(&source, "// Source: descriptors from github.com/ydb-platform/ydb-go-genproto.")
	fmt.Fprintln(&source)
	fmt.Fprintf(&source, "package %s\n", pkg)
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "import \"google.golang.org/protobuf/encoding/protowire\"")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "const (")
	for _, spec := range fields {
		field := spec.message.Fields().ByName(spec.name)
		if field == nil {
			return fmt.Errorf("%s.%s: field not found", spec.message.FullName(), spec.name)
		}
		if field.Kind() != spec.kind || field.IsList() != spec.repeated {
			return fmt.Errorf("%s: expected kind %s, repeated %t; got kind %s, repeated %t",
				field.FullName(), spec.kind, spec.repeated, field.Kind(), field.IsList())
		}
		wireType, err := wireTypeName(field.Kind())
		if err != nil {
			return fmt.Errorf("%s: %w", field.FullName(), err)
		}
		shape := ""
		if field.IsList() {
			shape = ", repeated"
		} else if oneof := field.ContainingOneof(); oneof != nil && !oneof.IsSynthetic() {
			shape = ", oneof"
		}
		fmt.Fprintf(&source, "\t%s protowire.Number = %d // %s; %s%s\n",
			spec.constant, field.Number(), field.FullName(), field.Kind(), shape)
		fmt.Fprintf(&source, "\t%sWireType protowire.Type = protowire.%s\n",
			strings.TrimSuffix(spec.constant, "Field"), wireType)
	}
	fmt.Fprintln(&source, ")")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func wireTypeName(kind protoreflect.Kind) (string, error) {
	switch kind {
	case protoreflect.BoolKind, protoreflect.EnumKind, protoreflect.Int32Kind,
		protoreflect.Int64Kind, protoreflect.Sint32Kind, protoreflect.Sint64Kind,
		protoreflect.Uint32Kind, protoreflect.Uint64Kind:
		return "VarintType", nil
	case protoreflect.Fixed32Kind, protoreflect.Sfixed32Kind, protoreflect.FloatKind:
		return "Fixed32Type", nil
	case protoreflect.Fixed64Kind, protoreflect.Sfixed64Kind, protoreflect.DoubleKind:
		return "Fixed64Type", nil
	case protoreflect.StringKind, protoreflect.BytesKind, protoreflect.MessageKind:
		return "BytesType", nil
	default:
		return "", fmt.Errorf("unsupported protobuf kind %s", kind)
	}
}
